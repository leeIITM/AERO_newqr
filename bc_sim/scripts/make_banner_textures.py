#!/usr/bin/env python3
"""Generate the ground-banner textures and models of the Gazebo world (bc_sim/models/*_banner_ground).

AeroTHON 2026 Mission 2 ground banners: 11.5 ft x 1 ft (3.5052 m x 0.3048 m), 1-inch white border,
"AEROTHON 2026" in white. Entry banner green #00B140, exit banner blue #0000FF.

    python3 scripts/make_banner_textures.py            # rewrites models/green_banner_ground, blue_banner_ground
"""
import os
import sys

import cv2
import numpy as np

LENGTH_M, WIDTH_M, BORDER_M, THICK_M = 3.5052, 0.3048, 0.0254, 0.01
PX_PER_M = 600
BANNERS = {
    "green_banner_ground": ((0x00, 0xB1, 0x40), "AeroTHON 2026 corridor entry banner (green #00B140), on the ground"),
    "blue_banner_ground": ((0x00, 0x00, 0xFF), "AeroTHON 2026 corridor exit banner (blue #0000FF), on the ground"),
}

MODEL_SDF = """<?xml version="1.0" encoding="UTF-8"?>
<sdf version="1.9">
  <!-- {desc}.
       {length} m x {width} m (11.5 ft x 1 ft), 1-inch white border, "AEROTHON 2026".
       Long side along the model's X axis; lies flat, top face at z = {thick}. Generated by
       bc_sim/scripts/make_banner_textures.py. -->
  <model name="{name}">
    <static>true</static>
    <link name="link">
      <visual name="visual">
        <cast_shadows>false</cast_shadows>
        <pose>0 0 {half} 0 0 0</pose>
        <geometry><box><size>{length} {width} {thick}</size></box></geometry>
        <material>
          <ambient>1 1 1 1</ambient>
          <diffuse>1 1 1 1</diffuse>
          <specular>0.05 0.05 0.05 1</specular>
          <pbr>
            <metal>
              <albedo_map>materials/textures/{name}.png</albedo_map>
              <roughness>0.9</roughness>
              <metalness>0.0</metalness>
            </metal>
          </pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
"""

MODEL_CONFIG = """<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>{desc}</description>
</model>
"""


FONTS = ["/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
         "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"]


def texture(rgb):
    """BGR image of the banner face: colour field, 1-inch white border, white text (an unslashed 0 for OCR)."""
    from PIL import Image, ImageDraw, ImageFont
    w, h = int(round(LENGTH_M * PX_PER_M)), int(round(WIDTH_M * PX_PER_M))
    b = int(round(BORDER_M * PX_PER_M))
    img = Image.new("RGB", (w, h), (255, 255, 255))
    draw = ImageDraw.Draw(img)
    draw.rectangle([b, b, w - b - 1, h - b - 1], fill=tuple(rgb))
    text = "AEROTHON 2026"
    path = next((f for f in FONTS if os.path.exists(f)), None)
    size = int(0.62 * (h - 2 * b))
    font = ImageFont.truetype(path, size) if path else ImageFont.load_default()
    x0, y0, x1, y1 = draw.textbbox((0, 0), text, font=font)
    draw.text(((w - (x1 - x0)) / 2 - x0, (h - (y1 - y0)) / 2 - y0), text, font=font, fill=(255, 255, 255))
    return cv2.cvtColor(np.asarray(img), cv2.COLOR_RGB2BGR)


def main(models_dir):
    for name, (rgb, desc) in BANNERS.items():
        d = os.path.join(models_dir, name)
        os.makedirs(os.path.join(d, "materials", "textures"), exist_ok=True)
        cv2.imwrite(os.path.join(d, "materials", "textures", f"{name}.png"), texture(rgb))
        with open(os.path.join(d, "model.sdf"), "w") as f:
            f.write(MODEL_SDF.format(name=name, desc=desc, length=LENGTH_M, width=WIDTH_M, thick=THICK_M,
                                     half=THICK_M / 2))
        with open(os.path.join(d, "model.config"), "w") as f:
            f.write(MODEL_CONFIG.format(name=name, desc=desc))
        print(f"wrote {d}")


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "models"))
