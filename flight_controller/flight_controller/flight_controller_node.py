"""The only node that commands ArduPilot (through MAVROS); every task flies the drone through it.

Actions (one goal at a time across all of them):
    ~/takeoff   mission_interfaces/Takeoff  set GUIDED, arm, GUIDED takeoff, then hold with setpoints
    ~/goto      mission_interfaces/GoTo     fly to a local-NED position or a body-frame offset
    ~/land      mission_interfaces/Land     descend in GUIDED, then disarm after touchdown

Flight modes (ArduCopter):
    GUIDED  the mission flies in GUIDED from before arming to touchdown: takeoff command, then
            position / velocity setpoints streamed on /mavros/setpoint_raw/local.
    AUTO    GoTo goals in FRAME_LOCAL_NED (coordinates generated by the mission or the search) are
            flown as a one-waypoint mission pushed with /mavros/mission/push, like suas_ardupilot
            does. The vehicle is back in GUIDED as soon as the waypoint is reached. FRAME_BODY_FLU
            offsets (small corrections from target_centering) stay GUIDED setpoints.
            goto_local_ned_mode / goto_body_mode choose "auto" or "guided" per frame.

With the parameter guided_only (default true) landing is done in GUIDED too. guided_only:=false
lands with ArduPilot's own LAND mode instead.

Topics:
    ~/pose          mission_interfaces/VehicleState (published)  local NED pose, heading, velocity,
                    height above the take-off pad (local z), armed / mode / ready. Every banner-corridor node reads the
                    drone pose from here (bench_flight_controller publishes the same topic).
    ~/setpoint      mission_interfaces/PositionSetpoint  streamed local-NED position + heading (target_search's
                    red-zone navigator, ~20 Hz). Same rules as cmd_vel_body: only while GUIDED is engaged and
                    no goal is active; if the stream stops for CMD_VEL_TIMEOUT the vehicle holds position.
    ~/cmd_vel_body  geometry_msgs/Twist     body-frame velocity, REP-103 FLU: linear.x forward,
                    linear.y left, linear.z up (m/s), angular.z yaw rate counter-clockwise (rad/s).
                    Used only while GUIDED is engaged and no goal is active. If commands stop for
                    CMD_VEL_TIMEOUT the vehicle holds its position.

If anything else takes the vehicle out of the mode we expect (pilot, failsafe), the controller
stops streaming and rejects GoTo goals: control is never taken back without a new Takeoff.
"""
import math
import threading
import time
import types

import rclpy
from geometry_msgs.msg import Point, Twist
from mavros_msgs.msg import PositionTarget
from mavros_msgs.srv import CommandBool, CommandTOL, SetMode, StreamRate, WaypointClear, WaypointPush
from mission_interfaces.action import GoTo, Land, Takeoff
from mission_interfaces.msg import PositionSetpoint, VehicleState
from sensor_msgs.msg import NavSatFix
from rclpy.action import ActionServer, CancelResponse, GoalResponse
from rclpy.callback_groups import ReentrantCallbackGroup
from rclpy.executors import MultiThreadedExecutor
from rclpy.node import Node

from flight_controller.ardupilot_utils import (
    MAV_CMD_CONDITION_YAW, MAV_CMD_DO_CHANGE_SPEED, MAV_CMD_NAV_LOITER_UNLIM, MAV_CMD_NAV_WAYPOINT,
    MAV_FRAME_MISSION, MAVROS_QOS, MODE_AUTO, MODE_GUIDED, MODE_LAND, LocalPositionFeed, VehicleMonitor,
    call_blocking, enu_flu_quaternion_to_rpy, gps_ok, make_setpoint, make_waypoint, offset_latlon, wrap_pi,
)

SETPOINT_RATE = 20.0  # Hz; ArduPilot stops a velocity setpoint after GUID_TIMEOUT (3 s by default)
CMD_VEL_TIMEOUT = 0.5  # s without /cmd_vel_body -> hold position
SERVICE_TIMEOUT = 1.0  # s to wait for one answer from a MAVROS service
RETRY_PAUSE = 0.5  # s between two tries of a refused request
COMMAND_TIMEOUT = 8.0  # s to get a request accepted (arming can be refused until the EKF is ready)
MODE_TIMEOUT = 5.0  # s for ArduPilot to report a requested mode / arming state
ACK_WAIT = 20.0  # s: arming and takeoff are sent ONCE and their acknowledgement awaited this long
ACK_REPORT = 2.0  # s between "still waiting for the acknowledgement" log lines
TAKEOFF_TIMEOUT = 120.0  # s
LAND_TIMEOUT = 120.0  # s
GOTO_EXTRA_TIME = 30.0  # s allowed beyond distance / speed
AUTO_START_TIME = 10.0  # s extra for an AUTO leg: mission upload and mode change
ALTITUDE_TOLERANCE = 0.5  # m, takeoff
TAKEOFF_STARTED_HEIGHT = 0.3  # m above the pad: the takeoff command was clearly accepted
SETTLED_SPEED = 0.3  # m/s, GoTo counts as arrived only below this speed
AIRBORNE_HEIGHT = 1.0  # m above home: armed and higher than this counts as flying
MIN_AUTO_ALTITUDE = 0.5  # m above home: an AUTO waypoint lower than this is refused
LAND_SLOW_HEIGHT = 2.0  # m above home: descend at land_speed below this, descent_speed above
LANDED_HEIGHT = 0.25  # m above home: touchdown if this low and not moving for LAND_SETTLE_TIME
LANDED_SPEED = 0.2  # m/s
LAND_SETTLE_TIME = 1.5  # s
YAW_ONLY_TOLERANCE = math.radians(3.0)  # an AUTO leg that is already there and within this of the yaw is skipped

NAN3 = [float("nan")] * 3
NO_GOAL = types.SimpleNamespace(is_cancel_requested=False)  # stand-in goal handle for internal waits


class FlightController(Node):
    def __init__(self):
        super().__init__("flight_controller")

        self.default_speed = self.declare_parameter("default_speed", 1.0).value  # m/s
        self.default_radius = self.declare_parameter("default_acceptance_radius", 0.3).value  # m
        self.max_speed = self.declare_parameter("max_speed", 3.0).value  # m/s, clamps GoTo and cmd_vel
        # Read at the start of each goal, so `ros2 param set` takes effect without a restart.
        self.declare_parameter("guided_only", True)  # land in GUIDED (see module doc)
        self.declare_parameter("goto_local_ned_mode", "guided")  # "auto" | "guided" for FRAME_LOCAL_NED goals
        self.declare_parameter("goto_body_mode", "guided")  # "auto" | "guided" for FRAME_BODY_FLU goals
        self.declare_parameter("descent_speed", 1.0)  # m/s GUIDED landing, above LAND_SLOW_HEIGHT
        self.declare_parameter("land_speed", 0.5)  # m/s final descent (ArduPilot's LAND_SPEED default is 0.5)
        self.declare_parameter("stream_rate_hz", 20)  # telemetry rate requested from ArduPilot; 0 = leave as is

        self.lock = threading.Lock()

        # ArduPilot telemetry
        self.vehicle = VehicleMonitor(self)
        self.local_pos = None  # LocalPose (NED, heading 0 = north clockwise)
        self.feed = LocalPositionFeed(self, self.local_pos_cb)
        self.takeoff_z = None  # local-NED z of the ground at take-off
        self.low_since = None  # touchdown detector

        # Setpoint streamed to ArduPilot: None (not streaming), "position", "velocity" or "land"
        # ("land" = hold x/y, descend at sp_velocity[2])
        self.sp_mode = None
        self.sp_position = list(NAN3)  # local NED
        self.sp_yaw = float("nan")
        self.sp_velocity = list(NAN3)  # local NED
        self.sp_yawspeed = float("nan")
        self.cmd_vel_stamp = 0.0
        self.guided_owned = False  # we engaged GUIDED and still have control
        self.expected_mode = MODE_GUIDED  # the mode we are flying in; GUIDED, or AUTO during a leg
        self.mode_switching = False  # a mode change is under way: do not call the old mode "lost"
        self.active_goal = None  # name of the running action, if any
        self.streams_requested = False

        self.setpoint_pub = self.create_publisher(PositionTarget, "/mavros/setpoint_raw/local", 10)
        self.pose_pub = self.create_publisher(VehicleState, "~/pose", 10)
        self.gps_fix = False
        self.create_subscription(NavSatFix, "/mavros/global_position/global", self.fix_cb, MAVROS_QOS)
        self.create_subscription(Twist, "~/cmd_vel_body", self.cmd_vel_cb, 10)
        self.create_subscription(PositionSetpoint, "~/setpoint", self.setpoint_cb, 10)
        self.setpoint_stamp = 0.0
        self.streaming = False  # following ~/setpoint

        self.set_mode_client = self.create_client(SetMode, "/mavros/set_mode")
        self.arm_client = self.create_client(CommandBool, "/mavros/cmd/arming")
        self.takeoff_client = self.create_client(CommandTOL, "/mavros/cmd/takeoff")
        self.clear_client = self.create_client(WaypointClear, "/mavros/mission/clear")
        self.push_client = self.create_client(WaypointPush, "/mavros/mission/push")
        self.stream_client = self.create_client(StreamRate, "/mavros/set_stream_rate")

        # Action executes block in their own threads; telemetry callbacks keep running meanwhile.
        actions = ReentrantCallbackGroup()
        for action_type, name, execute, cancel in (
            (Takeoff, "~/takeoff", self.execute_takeoff, self.accept_cancel),
            (GoTo, "~/goto", self.execute_goto, self.accept_cancel),
            (Land, "~/land", self.execute_land, self.reject_cancel),  # aborting a landing is unsafe
        ):
            ActionServer(
                self, action_type, name, execute_callback=execute,
                goal_callback=lambda goal, n=name: self.on_goal(n),
                cancel_callback=cancel, callback_group=actions,
            )

        self.create_timer(1.0 / SETPOINT_RATE, self.stream_setpoint)
        self.create_timer(2.0, self.request_streams)
        self.get_logger().info("Flight controller ready. Waiting for ArduPilot telemetry (MAVROS)...")

    # ---------------- ArduPilot callbacks ----------------

    def local_pos_cb(self, pose):
        self.local_pos = pose
        self.publish_pose(pose)

    def fix_cb(self, msg):
        self.gps_fix = gps_ok(msg)

    def publish_pose(self, pose):
        msg = VehicleState()
        msg.header.stamp = self.get_clock().now().to_msg()
        msg.header.frame_id = "local_ned"
        msg.valid = bool(pose.xy_valid and pose.z_valid)
        msg.ready = bool(self.vehicle.ready() and self.gps_fix)
        msg.armed = bool(self.vehicle.armed())
        msg.airborne = bool(self.airborne())
        msg.mode = self.vehicle.mode()
        msg.controller = "mavros"
        msg.x, msg.y, msg.z = float(pose.x), float(pose.y), float(pose.z)
        msg.heading = float(pose.heading)
        msg.vx, msg.vy, msg.vz = float(pose.vx), float(pose.vy), float(pose.vz)
        msg.alt_rel = float(self.height())
        roll, pitch, _ = enu_flu_quaternion_to_rpy(*pose.orientation)
        msg.roll, msg.pitch = float(roll), float(pitch)
        msg.xy_global = bool(pose.xy_global)
        if pose.xy_global:
            msg.ref_lat, msg.ref_lon = float(pose.ref_lat), float(pose.ref_lon)
        self.pose_pub.publish(msg)

    def request_streams(self):
        """Ask ArduPilot for fast telemetry once (its default stream rates are only a few Hz)."""
        rate = int(self.get_parameter("stream_rate_hz").value)
        if (self.streams_requested or rate <= 0 or not self.vehicle.connected()
                or not self.stream_client.service_is_ready()):
            return
        self.streams_requested = True
        self.stream_client.call_async(StreamRate.Request(stream_id=0, message_rate=rate, on_off=True))
        self.get_logger().info(f"Requested {rate} Hz telemetry streams from new ArduPilot.")

    # ---------------- velocity commands ----------------

    def cmd_vel_cb(self, msg: Twist):
        with self.lock:
            if not self.guided_owned or self.expected_mode != MODE_GUIDED or self.active_goal is not None:
                self.get_logger().warn(
                    "Ignoring cmd_vel_body: needs GUIDED engaged and no active goal.",
                    throttle_duration_sec=2.0,
                )
                return
            heading = self.local_pos.heading
            forward, left = self.clamp_horizontal(msg.linear.x, msg.linear.y)
            self.sp_mode = "velocity"
            self.sp_velocity = [
                forward * math.cos(heading) + left * math.sin(heading),
                forward * math.sin(heading) - left * math.cos(heading),
                -msg.linear.z,
            ]
            self.sp_yawspeed = -msg.angular.z  # FLU counter-clockwise -> NED clockwise
            self.cmd_vel_stamp = time.monotonic()

    def setpoint_cb(self, msg: PositionSetpoint):
        with self.lock:
            if not self.guided_owned or self.expected_mode != MODE_GUIDED or self.active_goal is not None:
                self.get_logger().warn(
                    "Ignoring ~/setpoint: needs GUIDED engaged and no active goal.", throttle_duration_sec=2.0)
                return
            self.sp_mode = "position"
            self.sp_position = [float(msg.x), float(msg.y), float(msg.z)]
            self.sp_yaw = float(msg.yaw) if math.isfinite(msg.yaw) else self.local_pos.heading
            self.setpoint_stamp = time.monotonic()
            self.streaming = True

    def clamp_horizontal(self, a, b):
        norm = math.hypot(a, b)
        if norm <= self.max_speed:
            return a, b
        return a * self.max_speed / norm, b * self.max_speed / norm

    # ---------------- setpoint streaming ----------------

    def stream_setpoint(self):
        with self.lock:
            if (self.guided_owned and not self.mode_switching and self.vehicle.state is not None
                    and self.vehicle.mode() != self.expected_mode):
                self.get_logger().warn(
                    f"Vehicle left {self.expected_mode} (now {self.vehicle.mode()}: pilot or failsafe). "
                    "Releasing control."
                )
                self.guided_owned = False
                self.sp_mode = None
                return
            if self.sp_mode is None or self.local_pos is None:
                return
            if self.sp_mode == "velocity" and time.monotonic() - self.cmd_vel_stamp > CMD_VEL_TIMEOUT:
                self.get_logger().info("cmd_vel_body stopped. Holding position.")
                self.hold_here_locked()
            if self.streaming and time.monotonic() - self.setpoint_stamp > CMD_VEL_TIMEOUT:
                self.streaming = False
                if self.active_goal is None:
                    self.get_logger().info("~/setpoint stream stopped. Holding position.")
                    self.hold_here_locked()

            stamp = self.get_clock().now().to_msg()
            if self.sp_mode == "position":
                msg = make_setpoint(stamp, "position", position=self.sp_position, heading=self.sp_yaw)
            elif self.sp_mode == "land":
                # ArduPilot cannot mix a position and a velocity axis: zero horizontal velocity + descent
                msg = make_setpoint(stamp, "velocity", velocity=(0.0, 0.0, self.sp_velocity[2]), yaw_rate=0.0)
            else:
                msg = make_setpoint(stamp, "velocity", velocity=self.sp_velocity, yaw_rate=self.sp_yawspeed)
            self.setpoint_pub.publish(msg)

    def hold_here_locked(self):
        """Hold the current position and heading. Caller holds self.lock."""
        pos = self.local_pos
        self.sp_mode = "position"
        self.sp_position = [pos.x, pos.y, pos.z]
        self.sp_yaw = pos.heading

    def hold_here(self):
        with self.lock:
            self.hold_here_locked()

    # ---------------- ArduPilot helpers (called from action threads) ----------------

    def armed(self):
        return self.vehicle.armed()

    def height(self):
        """Height above the take-off pad (m), or NaN.

        From the local z against the pad's z recorded at take-off: the same reference the mission uses for
        every leg (z = pad z - height), so the detectors' metres-per-pixel and the flown heights agree.
        Before the first take-off, ArduPilot's relative altitude."""
        pos = self.local_pos
        if pos is None:
            return float("nan")
        if self.takeoff_z is not None:
            return self.takeoff_z - pos.z
        return pos.rel_alt

    def airborne(self):
        height = self.height()
        return self.armed() and (self.vehicle.in_air() or (math.isfinite(height) and height > AIRBORNE_HEIGHT))

    def touched_down(self):
        """Landed according to ArduPilot, or at ground height and not moving for LAND_SETTLE_TIME."""
        if self.vehicle.on_ground():
            return True
        height = self.height()
        low = math.isfinite(height) and height < LANDED_HEIGHT and abs(self.local_pos.vz) < LANDED_SPEED
        if not low:
            self.low_since = None
            return False
        if self.low_since is None:
            self.low_since = time.monotonic()
        return time.monotonic() - self.low_since >= LAND_SETTLE_TIME

    def command(self, what, client, make_request, ok_field):
        """Send a MAVROS service request until ArduPilot accepts it. Returns an error string, or None."""
        deadline = time.monotonic() + COMMAND_TIMEOUT
        last = "no answer from MAVROS"
        while time.monotonic() < deadline:
            response = call_blocking(client, make_request(), timeout=SERVICE_TIMEOUT)
            if response is not None:
                if getattr(response, ok_field):
                    return None
                last = f"refused ({response})"
            time.sleep(RETRY_PAUSE)
        return f"{what}: {last}"

    def command_patiently(self, what, client, make_request, ok_field, done, goal_handle, abort=None):
        """Send `what` ONCE and wait up to ACK_WAIT s for ArduPilot's acknowledgement. Returns an error or None.

        A slow ACK (busy autopilot / companion computer) is not resent: a second request while MAVROS still
        waits for the first one's ACK is turned down by MAVROS ("already in progress") and was what made
        arming fail with "no answer from MAVROS". Only an explicit refusal (e.g. EKF not ready yet) is sent
        again, after RETRY_PAUSE, inside the same ACK_WAIT window.
        done(): the vehicle state shows the command took effect (e.g. armed): success even with no ACK.
        abort(): an error string if waiting is pointless (e.g. disarmed), else None."""
        start = time.monotonic()
        deadline = start + ACK_WAIT
        next_report = start + ACK_REPORT
        next_send = start
        future = None
        last = "no acknowledgement from ArduPilot"
        while True:
            now = time.monotonic()
            if done():
                if future is not None and now - start > 1.0:
                    self.get_logger().warn(f"{what}: no acknowledgement yet, but the vehicle state shows it "
                                           f"done after {now - start:.1f} s: continuing")
                return None
            if goal_handle.is_cancel_requested:
                return "canceled"
            if abort is not None:
                error = abort()
                if error:
                    return f"{what}: {error}"
            if future is not None and future.done():
                try:
                    response = future.result()
                except Exception as exc:  # noqa: BLE001 - MAVROS gave up (its own ACK timeout) or failed
                    response, last = None, f"MAVROS error ({exc})"
                future = None
                if response is not None:
                    if getattr(response, ok_field):
                        if now - start > ACK_REPORT:
                            self.get_logger().info(f"{what}: acknowledged after {now - start:.1f} s")
                        return None
                    last = f"refused ({response})"
                    self.get_logger().warn(f"{what}: {last}, trying again", throttle_duration_sec=2.0)
                next_send = now + RETRY_PAUSE
            if now >= deadline:
                return f"{what}: {last} within {ACK_WAIT:.0f} s"
            if future is None and now >= next_send:
                if client.service_is_ready():
                    future = client.call_async(make_request())
                else:
                    last = "MAVROS service not available"
                    next_send = now + 0.2
            if future is not None and now >= next_report:
                self.get_logger().info(f"{what}: waiting for ArduPilot's acknowledgement ({now - start:.0f} s / "
                                       f"{ACK_WAIT:.0f} s)")
                next_report += ACK_REPORT
            time.sleep(0.05)

    def set_arming(self, value):
        return self.command(
            "arm" if value else "disarm", self.arm_client, lambda: CommandBool.Request(value=bool(value)), "success"
        )

    def switch_mode(self, mode, goal_handle):
        """Change the flight mode and wait until ArduPilot reports it. Returns an error string, or None."""
        self.mode_switching = True
        try:
            if self.vehicle.mode() != mode:
                error = self.command(
                    f"set mode {mode}", self.set_mode_client,
                    lambda: SetMode.Request(base_mode=0, custom_mode=mode), "mode_sent",
                ) or self.wait_until(lambda: self.vehicle.mode() == mode, MODE_TIMEOUT, goal_handle)
                if error is not None:
                    return error
            self.expected_mode = mode
            return None
        finally:
            self.mode_switching = False

    def wait_until(self, condition, timeout, goal_handle, on_tick=None):
        """Poll until condition() is true. Returns None, or 'timeout' / 'canceled' / 'guided mode lost'."""
        deadline = time.monotonic() + timeout
        must_own_guided = self.guided_owned
        while not condition():
            if goal_handle.is_cancel_requested:
                return "canceled"
            if must_own_guided and not self.guided_owned:
                return "guided mode lost"
            if time.monotonic() > deadline:
                return "timeout"
            if on_tick:
                on_tick()
            time.sleep(1.0 / SETPOINT_RATE)
        return None

    def back_to_guided(self):
        """After an AUTO leg: GUIDED again and hold where we are. No-op if the pilot has taken over."""
        if not self.guided_owned:
            return
        if self.switch_mode(MODE_GUIDED, NO_GOAL) is None:
            self.hold_here()
        else:
            self.get_logger().error("Could not return to GUIDED after the AUTO leg.")

    # ---------------- action plumbing ----------------

    def on_goal(self, name):
        with self.lock:
            if self.vehicle.state is None or self.local_pos is None:
                self.get_logger().warn(f"Rejecting {name}: no ArduPilot telemetry yet.")
                return GoalResponse.REJECT
            if self.active_goal is not None:
                self.get_logger().warn(f"Rejecting {name}: {self.active_goal} is running.")
                return GoalResponse.REJECT
            self.active_goal = name
            self.streaming = False  # a goal takes over from a setpoint stream
        return GoalResponse.ACCEPT

    def accept_cancel(self, goal_handle):
        return CancelResponse.ACCEPT

    def reject_cancel(self, goal_handle):
        return CancelResponse.REJECT

    def finish(self, goal_handle, result, error=None):
        """Complete the goal (error None = success) and free the controller for the next goal."""
        result.success = error is None
        result.message = error or "ok"
        if error is None:
            goal_handle.succeed()
        elif goal_handle.is_cancel_requested:
            goal_handle.canceled()
        else:
            goal_handle.abort()
            self.get_logger().error(f"{self.active_goal} failed: {error}")
        with self.lock:
            self.active_goal = None
        return result

    # ---------------- Takeoff ----------------

    def execute_takeoff(self, goal_handle):
        result = Takeoff.Result()
        altitude = goal_handle.request.altitude
        self.get_logger().info(f"Takeoff: climbing {altitude:.1f} m")

        if altitude <= ALTITUDE_TOLERANCE:
            return self.finish(goal_handle, result, f"altitude must be > {ALTITUDE_TOLERANCE} m")
        if self.airborne():
            return self.finish(goal_handle, result, "already airborne")
        pos = self.local_pos
        if not (pos.xy_valid and pos.z_valid and pos.global_valid and math.isfinite(pos.rel_alt)):
            return self.finish(goal_handle, result, "no valid position / relative altitude from ArduPilot (GPS fix?)")

        # GUIDED first: ArduPilot arms and takes off from it, and the mission stays in it.
        error = self.switch_mode(MODE_GUIDED, goal_handle)
        if error is None:
            error = self.command_patiently(
                "arm", self.arm_client, lambda: CommandBool.Request(value=True), "success", self.armed, goal_handle)
        if error is None:
            error = self.wait_until(self.armed, MODE_TIMEOUT, goal_handle)
        if error is not None:
            return self.finish(goal_handle, result, f"arming: {error}")
        with self.lock:
            self.guided_owned = True
            self.expected_mode = MODE_GUIDED
        self.low_since = None

        # Send the takeoff right away: ArduPilot disarms again after DISARM_DELAY (10 s) on the ground.
        pos = self.local_pos
        self.takeoff_z = pos.z
        target_rel = pos.rel_alt + altitude  # takeoff altitude is metres above home
        error = self.command_patiently(
            "takeoff", self.takeoff_client,
            lambda: CommandTOL.Request(min_pitch=0.0, yaw=0.0, latitude=0.0, longitude=0.0, altitude=float(target_rel)),
            "success",
            lambda: self.height() > TAKEOFF_STARTED_HEIGHT,  # climbing: accepted even if the ACK was lost
            goal_handle,
            abort=lambda: None if self.armed() else "vehicle disarmed while waiting for the takeoff to be accepted",
        )
        if error is not None:
            self.set_arming(False)  # armed on the ground: disarm rather than wait for ArduPilot
            with self.lock:
                self.guided_owned = False
            return self.finish(goal_handle, result, error)

        feedback = Takeoff.Feedback()

        def climbing():
            if not self.armed():
                raise RuntimeError("vehicle disarmed during takeoff")
            feedback.altitude_remaining = float(max(0.0, altitude - self.height()))
            goal_handle.publish_feedback(feedback)

        try:
            error = self.wait_until(
                lambda: self.height() >= altitude - ALTITUDE_TOLERANCE,
                TAKEOFF_TIMEOUT, goal_handle, climbing,
            )
        except RuntimeError as e:
            error = str(e)
        if error is not None:
            if self.guided_owned:
                self.hold_here()  # stay in GUIDED, holding where we are
            return self.finish(goal_handle, result, f"climb: {error}")

        self.hold_here()  # from now on GUIDED setpoints
        self.get_logger().info(f"Takeoff complete at {self.height():.1f} m above the pad. GUIDED, holding.")
        return self.finish(goal_handle, result)

    # ---------------- GoTo ----------------

    def execute_goto(self, goal_handle):
        req = goal_handle.request
        result = GoTo.Result()
        if not self.guided_owned:
            return self.finish(goal_handle, result, "GUIDED not engaged (run Takeoff first)")

        pos = self.local_pos
        start = (pos.x, pos.y, pos.z)
        heading = pos.heading
        if req.frame == GoTo.Goal.FRAME_LOCAL_NED:
            # NaN components keep the current value, e.g. pure altitude changes.
            target = tuple(t if math.isfinite(t) else c for t, c in zip((req.x, req.y, req.z), start))
            yaw = req.yaw if math.isfinite(req.yaw) else heading
            method = str(self.get_parameter("goto_local_ned_mode").value).lower()
        elif req.frame == GoTo.Goal.FRAME_BODY_FLU:
            target = (
                pos.x + req.x * math.cos(heading) + req.y * math.sin(heading),
                pos.y + req.x * math.sin(heading) - req.y * math.cos(heading),
                pos.z - req.z,
            )
            yaw = wrap_pi(heading - req.yaw) if math.isfinite(req.yaw) else heading
            method = str(self.get_parameter("goto_body_mode").value).lower()
        else:
            return self.finish(goal_handle, result, f"unknown frame {req.frame}")
        if method not in ("auto", "guided"):
            return self.finish(goal_handle, result, f"goto mode must be 'auto' or 'guided', not '{method}'")

        speed = min(req.speed if req.speed > 0.0 else self.default_speed, self.max_speed)
        radius = req.acceptance_radius if req.acceptance_radius > 0.0 else self.default_radius
        delta = [t - s for t, s in zip(target, start)]
        total = math.sqrt(sum(d * d for d in delta))
        self.get_logger().info(
            f"GoTo N={target[0]:.1f} E={target[1]:.1f} D={target[2]:.1f} "
            f"yaw={math.degrees(yaw):.0f} deg ({total:.1f} m at {speed:.1f} m/s, {method.upper()})"
        )
        if method == "auto":
            return self.goto_auto(goal_handle, result, target, yaw, speed, radius, total)
        return self.goto_guided(goal_handle, result, start, target, delta, yaw, speed, radius, total)

    def goto_guided(self, goal_handle, result, start, target, delta, yaw, speed, radius, total):
        """Position setpoint that moves along the line at `speed` (GUIDED)."""
        with self.lock:
            self.sp_mode = "position"
            self.sp_yaw = yaw
        started = time.monotonic()
        feedback = GoTo.Feedback()

        def advance():
            # Move the setpoint along the line at `speed` instead of jumping to the target,
            # which ArduPilot would fly at its own waypoint speed.
            progress = min(total, speed * (time.monotonic() - started))
            fraction = progress / total if total > 0.0 else 1.0
            with self.lock:
                self.sp_position = [s + d * fraction for s, d in zip(start, delta)]
            feedback.distance_remaining = float(self.distance_to(target))
            goal_handle.publish_feedback(feedback)

        def arrived():
            p = self.local_pos
            return (
                time.monotonic() - started >= total / speed
                and self.distance_to(target) < radius
                and math.sqrt(p.vx ** 2 + p.vy ** 2 + p.vz ** 2) < SETTLED_SPEED
            )

        error = self.wait_until(arrived, total / speed + GOTO_EXTRA_TIME, goal_handle, advance)
        if error is not None:
            if self.guided_owned:
                self.hold_here()
            return self.finish(goal_handle, result, error)
        return self.goto_done(goal_handle, result)

    def goto_auto(self, goal_handle, result, target, yaw, speed, radius, total):
        """One-waypoint mission in AUTO (as suas_ardupilot flies its coordinates), then back to GUIDED."""
        pos = self.local_pos
        if not (pos.global_valid and math.isfinite(pos.rel_alt)):
            return self.finish(goal_handle, result, "AUTO leg needs a GPS fix and relative altitude from ArduPilot")
        yaw_change = wrap_pi(yaw - pos.heading)
        if (total < radius and abs(yaw_change) < YAW_ONLY_TOLERANCE
                and math.hypot(pos.vx, pos.vy) < SETTLED_SPEED and abs(pos.vz) < SETTLED_SPEED):
            self.get_logger().info("Already there; GoTo skipped.")
            return self.goto_done(goal_handle, result)
        lat, lon = offset_latlon(pos.lat, pos.lon, target[0] - pos.x, target[1] - pos.y)
        rel_alt = pos.rel_alt + (pos.z - target[2])  # NED z points down
        if rel_alt < MIN_AUTO_ALTITUDE:
            return self.finish(goal_handle, result, f"AUTO waypoint would be {rel_alt:.1f} m above home")

        mission = [
            # ArduPilot reads item 0 of an uploaded mission as home, not as a waypoint to fly to.
            make_waypoint(MAV_CMD_NAV_WAYPOINT, lat=pos.lat, lon=pos.lon, alt=0.0, current=True),
            make_waypoint(MAV_CMD_DO_CHANGE_SPEED, frame=MAV_FRAME_MISSION, p1=1.0, p2=speed, p3=-1.0),
            make_waypoint(
                MAV_CMD_CONDITION_YAW, frame=MAV_FRAME_MISSION,
                p1=math.degrees(yaw) % 360.0, p2=0.0, p3=1.0 if yaw_change >= 0.0 else -1.0, p4=0.0,
            ),
            make_waypoint(MAV_CMD_NAV_WAYPOINT, p1=0.0, p2=radius, lat=lat, lon=lon, alt=rel_alt),
            # Never let the mission finish: ArduCopter flies RTL at the end of a mission.
            make_waypoint(MAV_CMD_NAV_LOITER_UNLIM, lat=lat, lon=lon, alt=rel_alt),
        ]

        with self.lock:
            self.sp_mode = None  # stop streaming; GUIDED keeps the last position target meanwhile
        error = self.upload_mission(mission) or self.switch_mode(MODE_AUTO, goal_handle)
        if error is not None:
            self.back_to_guided()
            return self.finish(goal_handle, result, error)

        feedback = GoTo.Feedback()

        def report():
            feedback.distance_remaining = float(self.distance_to(target))
            goal_handle.publish_feedback(feedback)

        def arrived():
            p = self.local_pos
            return self.distance_to(target) < radius and math.sqrt(p.vx ** 2 + p.vy ** 2 + p.vz ** 2) < SETTLED_SPEED

        error = self.wait_until(arrived, total / speed + GOTO_EXTRA_TIME + AUTO_START_TIME, goal_handle, report)
        self.back_to_guided()  # also on failure or cancel: never leave the vehicle in AUTO
        if error is not None:
            return self.finish(goal_handle, result, error)
        return self.goto_done(goal_handle, result)

    def upload_mission(self, mission):
        """Replace the mission on the autopilot. Returns an error string, or None."""
        if call_blocking(self.clear_client, WaypointClear.Request(), timeout=5.0) is None:
            return "mission clear: no answer from MAVROS"
        response = call_blocking(self.push_client, WaypointPush.Request(start_index=0, waypoints=mission), timeout=10.0)
        if response is None:
            return "mission upload: no answer from MAVROS"
        if not response.success:
            return "mission upload: refused by ArduPilot"
        return None

    def goto_done(self, goal_handle, result):
        p = self.local_pos
        result.final_position = Point(x=float(p.x), y=float(p.y), z=float(p.z))
        self.get_logger().info("GoTo reached.")
        return self.finish(goal_handle, result)

    def distance_to(self, target):
        p = self.local_pos
        return math.sqrt((target[0] - p.x) ** 2 + (target[1] - p.y) ** 2 + (target[2] - p.z) ** 2)

    # ---------------- Land ----------------

    def execute_land(self, goal_handle):
        result = Land.Result()
        if not self.armed():
            return self.finish(goal_handle, result)  # already on the ground and disarmed

        if self.get_parameter("guided_only").value:
            if self.guided_owned:
                return self.land_guided(goal_handle, result)
            self.get_logger().warn("GUIDED is not engaged: landing with ArduPilot LAND mode instead.")
        return self.land_mode(goal_handle, result)

    def land_guided(self, goal_handle, result):
        """Descend in GUIDED holding x/y, then disarm once the vehicle is on the ground."""
        land_speed = float(self.get_parameter("land_speed").value)
        descent_speed = max(float(self.get_parameter("descent_speed").value), land_speed)
        if land_speed <= 0.0:
            return self.finish(goal_handle, result, "land_speed must be > 0")
        self.get_logger().info(f"Landing in GUIDED (final descent {land_speed:.1f} m/s)...")
        self.low_since = None
        with self.lock:
            self.sp_mode = "land"
            self.sp_velocity = [0.0, 0.0, land_speed]
        feedback = Land.Feedback()

        def descending():
            height = self.height()
            high = math.isfinite(height) and height > LAND_SLOW_HEIGHT
            with self.lock:
                self.sp_velocity[2] = descent_speed if high else land_speed
            feedback.altitude = float(height if math.isfinite(height) else -self.local_pos.z)
            goal_handle.publish_feedback(feedback)

        error = self.wait_until(lambda: self.touched_down() or not self.armed(), LAND_TIMEOUT, goal_handle, descending)
        if error is not None:
            if self.guided_owned:
                self.hold_here()
            return self.finish(goal_handle, result, error)
        return self.disarm_after_touchdown(goal_handle, result)

    def land_mode(self, goal_handle, result):
        """ArduPilot's own LAND mode; it disarms itself shortly after touchdown."""
        self.get_logger().info("Landing (LAND mode)...")
        self.low_since = None
        with self.lock:
            self.sp_mode = None
        error = self.switch_mode(MODE_LAND, goal_handle)
        if error is not None:
            if self.guided_owned:
                self.hold_here()
            return self.finish(goal_handle, result, f"land mode: {error}")
        with self.lock:  # ArduPilot is landing by itself now; stop watching the mode
            self.guided_owned = False
        feedback = Land.Feedback()

        def descending():
            feedback.altitude = float(max(0.0, self.height()))
            goal_handle.publish_feedback(feedback)

        error = self.wait_until(lambda: self.touched_down() or not self.armed(), LAND_TIMEOUT, goal_handle, descending)
        if error is not None:
            return self.finish(goal_handle, result, error)
        return self.disarm_after_touchdown(goal_handle, result)

    def disarm_after_touchdown(self, goal_handle, result):
        if self.armed():  # ArduPilot may already have disarmed itself (DISARM_DELAY)
            self.get_logger().info("Touchdown. Disarming...")
            error = self.set_arming(False)
            if error is None or not self.armed():
                error = self.wait_until(lambda: not self.armed(), MODE_TIMEOUT, goal_handle)
            if error is not None and self.armed():
                return self.finish(goal_handle, result, f"disarm: {error}")
        with self.lock:  # on the ground and disarmed: stop streaming
            self.guided_owned = False
            self.sp_mode = None
        self.get_logger().info("Landed and disarmed.")
        return self.finish(goal_handle, result)


def main(args=None):
    rclpy.init(args=args)
    node = FlightController()
    executor = MultiThreadedExecutor()
    executor.add_node(node)
    try:
        executor.spin()
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        if rclpy.ok():
            rclpy.shutdown()


if __name__ == "__main__":
    main()
